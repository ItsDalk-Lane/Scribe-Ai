export function activeMode(intent: TaskRequest['intent'], mode: ExecutionMode | undefined, sideChat?: boolean, goalRound?: true,
	available?: { plan: boolean; goalReport: boolean }): string {
	if (intent === 'review') return '本次为只读笔记检查。仅检查用户选中的资料，按证据列出可修正的问题和影响。';
	if (sideChat) return '本次为只读侧聊。只处理当前问题，主聊天记录和引文仅供参考。';
	if (intent === 'plan') return '本次为只读计划模式。可以核对库内资料，整理计划和草案待办，等待用户批准。'
		+ (available?.plan === false ? '本轮无计划提交工具，请按系统提示的计划文本格式提交。' : '');
	const name = mode === 'full-access' ? '完全访问' : mode === 'auto-review' ? '自动审核' : '询问审批';
	const report = available?.goalReport === false ? '请按系统提示用文本回执提交报告。'
		: '尚未收到本轮报告成功回执时，用 ReportGoal 提交已核对事项和剩余工作。收到成功回执后，用普通正文简述进展。';
	return `当前权限模式为${name}。${goalRound ? '这是聊天目标的自动执行轮次，请按编号验收条件继续。' + report : ''}`;
}
